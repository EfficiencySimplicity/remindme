// A fun little exit-with-error function
void whoops(char *msg) {
    if (strlen(msg) != 0) {fprintf(stderr, "%s\n", msg);}
    // https://www.tutorialspoint.com/c_standard_library/c_function_exit.htm
    exit(EXIT_FAILURE);
}

// Useful for reading files
void* whoops_if_null(void* item, char *msg) {
    if (item == NULL) {whoops(msg);}
    return item;
}

// https://stackoverflow.com/questions/238603/how-can-i-get-a-files-size-in-c
// such odd styling, you can tell this code is copy-pasted. How mundane.
int fsize(FILE *fp){
    int prev=ftell(fp);
    fseek(fp, 0L, SEEK_END);
    int sz=ftell(fp);
    fseek(fp,prev,SEEK_SET); //go back to where we were
    return sz;
}

// A (slightly) shorter way to compare 2 strings
bool streq(char *s1, char *s2) {
    return strcmp(s1, s2) == 0;
}

// Finds a string in a file; leaves the file pointer at the end of the found string if it is found,
// or at the end of the file if it is not found. Starts from where the file pointer is already.
bool strinf(char *s, FILE *f) {
    // This is all the buffer space we really need to check if they're equal
    // https://stackoverflow.com/questions/29717970/do-i-need-to-free-char-array-of-fixed-length
    char line[strlen(s) + 1];

    // https://www.geeksforgeeks.org/c/read-a-file-line-by-line-in-c/
    while (fgets(line, sizeof(line), f)) {
        if (streq(line, s)) {return true;}
    }
    return false;
}

// removes a string from a file, starting the search from the current position of the pointer
// The file must be open for reading and writing; i.e. r+
// This truncates the file, so any saved length variables may be invalid.
void stremf(char *s, FILE *f) {

    // This tells us if the string is in the file
    // ALONG with setting the position of the pointer to where the string ends
    bool found = strinf(s, f);
    if (!found) {return;}

    int s_len  = strlen(s);
    int length = fsize(f);
    long pos   = ftell(f);
    
    char end_buffer[length-pos];
    char start_buffer[pos-s_len];

    fread(end_buffer, sizeof(char), length-pos, f);
    rewind(f);
    fread(start_buffer, sizeof(char), pos-s_len, f);
    rewind(f);

    fwrite(start_buffer, sizeof(char), pos-s_len, f);
    fwrite(end_buffer, sizeof(char), length-pos, f);

    ftruncate(fileno(f), length - s_len);
}

// This lets me concat strings easily without dealing with char array size limits
// It invalidates the old pointer, I believe, so you gotta feed this back into the
// first string being concatted; i.e. `text = concat(text, "abc");`
// https://stackoverflow.com/questions/8465006/how-do-i-concatenate-two-strings-in-c
char* concat(char *s1, char *s2)
{
    // https://www.w3schools.com/c/c_memory_reallocate.php
    s1 = whoops_if_null(
        realloc(s1, strlen(s1) + strlen(s2) + 1), // +1 for the null-terminator
        "There was a memory allocation error! Sorry!"
    );
        
    strcat(s1, s2);

    // The original pointer must be set to this return value
    return s1;
}

// prepends the home directory to a string
char* in_home(char *s) {
    return concat(strdup(getenv("HOME")), s);
}

// Adds the line to the file, making sure it gets its own line
void add_line(char *s, FILE *f) {
    // mumblemumbleaddnewlineandallthat
    if (fsize(f) != 0) {
        fseek(f, -sizeof(char), SEEK_END);
        // https://stackoverflow.com/questions/22621952/convert-char-to-string-in-c
        char last[2] = "\0"; /* gives {\0, \0} */
        last[0] = fgetc(f);

        fseek(f, 0, SEEK_END);
        if (!streq(last, "\n")) {fputc('\n', f);}
    }

    fwrite(s, sizeof(char), strlen(s), f);
}


